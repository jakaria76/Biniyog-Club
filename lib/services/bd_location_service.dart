  // Helper to localize string based on language
  static String localize(String englishName) {
    if (LanguageService.isBangla) {
      return _bnTranslations[englishName] ?? englishName;
    }
    return englishName;
  }

  // Get all Divisions (Localized)
  static List<String> getDivisions() {
    final list = _bdData.keys.toList();
    if (LanguageService.isBangla) {
      return list.map((e) => localize(e)).toList();
    }
    return list;
  }

  // Find English Division Key from Localized or English Input
  static String? _findDivisionKey(String? divisionInput) {
    if (divisionInput == null) return null;
    if (_bdData.containsKey(divisionInput)) return divisionInput;
    for (final entry in _bnTranslations.entries) {
      if (entry.value == divisionInput && _bdData.containsKey(entry.key)) {
        return entry.key;
      }
    }
    return divisionInput;
  }

  // Find English District Key
  static String? _findDistrictKey(String? divisionKey, String? districtInput) {
    if (divisionKey == null || districtInput == null) return null;
    final districts = _bdData[divisionKey];
    if (districts == null) return null;
    if (districts.containsKey(districtInput)) return districtInput;
    for (final entry in _bnTranslations.entries) {
      if (entry.value == districtInput && districts.containsKey(entry.key)) {
        return entry.key;
      }
    }
    return districtInput;
  }

  // Get Districts for a given Division
  static List<String> getDistricts(String? division) {
    final divKey = _findDivisionKey(division);
    if (divKey == null || !_bdData.containsKey(divKey)) {
      return [];
    }
    final list = _bdData[divKey]!.keys.toList();
    if (LanguageService.isBangla) {
      return list.map((e) => localize(e)).toList();
    }
    return list;
  }

  // Get Upazilas / Thanas for a given Division and District
  static List<String> getUpazilas(String? division, String? district) {
    final divKey = _findDivisionKey(division);
    final distKey = _findDistrictKey(divKey, district);

    if (divKey == null || distKey == null) return [];
    final districts = _bdData[divKey];
    if (districts == null || !districts.containsKey(distKey)) {
      return [];
    }
    final list = districts[distKey]!;
    if (LanguageService.isBangla) {
      return list.map((e) => localize(e)).toList();
    }
    return list;
  }

